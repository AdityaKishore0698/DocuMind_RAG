#!/usr/bin/env bash
# Generate the local configuration files from the running local Supabase stack:
#   .env.local            backend (API + worker containers, read by docker compose)
#   frontend/.env.local   Next.js (browser)
#
# Run from the repository root after `supabase start`. Existing files are kept unless --force is given.
# Everything written here is local-development configuration (the Supabase CLI's local demo keys);
# both files are git-ignored.
set -euo pipefail

cd "$(dirname "$0")/.."
FORCE=0
[[ "${1:-}" == "--force" ]] && FORCE=1

if command -v supabase >/dev/null 2>&1; then
  SUPABASE=(supabase)
else
  SUPABASE=(npx --yes supabase)
fi

status_env="$("${SUPABASE[@]}" status -o env 2>/dev/null)" || {
  echo "error: the local Supabase stack is not running — run 'supabase start' first." >&2
  exit 1
}
# KEY="value" lines; read only the variables this script needs.
get() { printf '%s\n' "$status_env" | sed -n "s/^$1=\"\{0,1\}\([^\"]*\)\"\{0,1\}$/\1/p" | head -n1; }
API_URL="$(get API_URL)"
DB_URL="$(get DB_URL)"
ANON_KEY="$(get ANON_KEY)"
SERVICE_ROLE_KEY="$(get SERVICE_ROLE_KEY)"
JWT_SECRET="$(get JWT_SECRET)"
for v in API_URL DB_URL ANON_KEY SERVICE_ROLE_KEY JWT_SECRET; do
  [[ -n "${!v}" ]] || { echo "error: '${SUPABASE[*]} status -o env' did not report $v" >&2; exit 1; }
done
case "$API_URL" in
  http://127.0.0.1:*|http://localhost:*) ;;
  *) echo "error: Supabase API_URL ($API_URL) is not local — refusing to write configuration." >&2; exit 1 ;;
esac

# Containers reach host services through host.docker.internal.
to_container() { printf '%s' "$1" | sed -e 's#127\.0\.0\.1#host.docker.internal#' -e 's#localhost#host.docker.internal#'; }

write() {  # write <path> <content>
  if [[ -e "$1" && $FORCE -eq 0 ]]; then
    echo "kept existing $1 (use --force to regenerate)"
  else
    umask 077
    printf '%s\n' "$2" > "$1"
    echo "wrote $1"
  fi
}

write .env.local "# Generated by scripts/setup_local_env.sh from 'supabase status' — local development only.
# Backend configuration for the api and worker containers (docker compose reads this file).

# Local Supabase: Postgres + pgvector, auth (HS256 demo secret), private storage bucket 'documents'
DATABASE_URL=$(to_container "$DB_URL")
SUPABASE_URL=$(to_container "$API_URL")
SUPABASE_SERVICE_ROLE_KEY=$SERVICE_ROLE_KEY
SUPABASE_JWT_SECRET=$JWT_SECRET

# Local inference through Ollama on the host (see README: Local models)
INFERENCE_PROVIDER=ollama
OLLAMA_BASE_URL=http://host.docker.internal:11434
OLLAMA_CHAT_MODEL=qwen3:8b
OLLAMA_EMBEDDING_MODEL=nomic-embed-text
OLLAMA_KEEP_ALIVE=10m

# Behaviour (defaults shown)
RETRIEVAL_MODE=vector
AGENT_ENABLED=false
FRONTEND_ORIGINS=http://localhost:3000"

write frontend/.env.local "# Generated by scripts/setup_local_env.sh from 'supabase status' — local development only.
NEXT_PUBLIC_API_URL=http://localhost:8000
NEXT_PUBLIC_SUPABASE_URL=$API_URL
NEXT_PUBLIC_SUPABASE_ANON_KEY=$ANON_KEY
NEXT_PUBLIC_ENABLE_GOOGLE_AUTH=false"
